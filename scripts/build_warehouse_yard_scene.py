def rot_y_transform(angle_deg, x, y, z):
    rad = math.radians(angle_deg)
    c = math.cos(rad)
    s = math.sin(rad)
    # Transform3D(c, 0, s, 0, 1, 0, -s, 0, c, x, y, z)
    return f"Transform3D({c:.6f}, 0, {s:.6f}, 0, 1, 0, {-s:.6f}, 0, {c:.6f}, {x:.2f}, {y:.2f}, {z:.2f})"

